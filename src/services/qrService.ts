import { api, absoluteMediaUrl } from "@/lib/apiClient";
import { qrFromApi, qrMetricsFromApi } from "@/lib/mappers/shop";
import { useAuthStore } from "@/stores/useAuthStore";
import type { ComercQR, QRMetrics } from "@/types/merchant";
import type { ApiQr } from "@/types/api";

async function fetchAuthorizedBlob(url: string): Promise<Blob> {
  const token = useAuthStore.getState().token;
  const res = await fetch(url, {
    headers: token ? { Authorization: `Bearer ${token}` } : {},
  });
  if (!res.ok) throw new Error("qr_download_failed");
  return res.blob();
}

export const qrService = {
  async getMyQR(): Promise<ComercQR> {
    const qr = await api.get<ApiQr>("/shops/me/qr");
    return qrFromApi(qr);
  },

  /** Single GET /shops/me/qr → QR payload + visit metrics (avoids double fetch). */
  async getMyQRPage(): Promise<{ qr: ComercQR; metrics: QRMetrics }> {
    const raw = await api.get<ApiQr>("/shops/me/qr");
    return { qr: qrFromApi(raw), metrics: qrMetricsFromApi(raw) };
  },

  /**
   * The QR picture as a local address an <img> can show.
   *
   * The API only hands the picture to the shop itself (it is the scan code),
   * so it cannot be an `<img src>` to the API: it is fetched with the session
   * and kept in memory.
   */
  async getImageUrl(pngUrl: string): Promise<string> {
    return URL.createObjectURL(await fetchAuthorizedBlob(pngUrl));
  },

  async getMetrics(): Promise<QRMetrics> {
    const { metrics } = await qrService.getMyQRPage();
    return metrics;
  },

  async downloadPDF(): Promise<void> {
    // PDF not yet generated by the API — fall back to PNG.
    await qrService.downloadPNG();
  },

  async downloadPNG(): Promise<void> {
    const qr = await api.get<ApiQr>("/shops/me/qr");
    const url = absoluteMediaUrl(qr.png_url);
    if (!url) throw new Error("qr_png_missing");
    const blob = await fetchAuthorizedBlob(url);
    const objectUrl = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = objectUrl;
    a.download = `qr-${qr.qr_code}.png`;
    a.click();
    URL.revokeObjectURL(objectUrl);
  },

  async print(): Promise<void> {
    const qr = await api.get<ApiQr>("/shops/me/qr");
    const url = absoluteMediaUrl(qr.png_url);
    if (!url) throw new Error("qr_png_missing");
    const blob = await fetchAuthorizedBlob(url);
    const objectUrl = URL.createObjectURL(blob);
    const win = window.open(objectUrl, "_blank");
    win?.addEventListener("load", () => {
      win.print();
      URL.revokeObjectURL(objectUrl);
    });
  },

  async regenerate(): Promise<ComercQR> {
    const qr = await api.post<ApiQr>("/shops/me/qr");
    return qrFromApi(qr);
  },
};
